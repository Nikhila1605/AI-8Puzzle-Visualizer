function generateRandom() {
  const goalCheck = validateCells(readGrid('goal'), 'Goal state');
  if (!goalCheck.ok) { showMessage('error', goalCheck.error + ' Fix the goal first.'); return; }

  const mode = $('randomMode').value;
  let start;
  do {
    start = mode === 'any' ? randomSolvablePuzzle(goalCheck.state) : randomWalkPuzzle(goalCheck.state, Number(mode));
  } while (start === goalCheck.state); // avoid an already-solved puzzle
  setGrid('start', start);
  showMessage('ok', mode === 'any'
    ? 'Random solvable puzzle generated (inversion parity matches the goal). Deep ones may take up to a second.'
    : `Generated by making ${mode} random legal moves from the goal, so it is solvable. BFS may find a shorter way back.`);
}

// ================= Running BFS =================
function runSearch() {
  const startCheck = validateCells(readGrid('start'), 'Initial state');
  if (!startCheck.ok) { showMessage('error', startCheck.error); return; }
  const goalCheck = validateCells(readGrid('goal'), 'Goal state');
  if (!goalCheck.ok) { showMessage('error', goalCheck.error); return; }

  const start = startCheck.state;
  const goal = goalCheck.state;
  const solvable = isSolvable(start, goal);
  if (!solvable && !$('skipCheck').checked) {
    showMessage('error',
      `This puzzle cannot be solved: the initial state has ${countInversions(start)} inversions and the goal has ` +
      `${countInversions(goal)}. One is odd and one is even, and no sequence of moves can change that.`);
    return;
  }

  showMessage('info', 'Searching...');
  $('btnRun').disabled = true;
  searchPlayer.stop();
  solutionPlayer.stop();

  // Let the browser paint "Searching..." before the (possibly long) search.
  setTimeout(() => {
    result = bfsSolve(start, goal);
    $('btnRun').disabled = false;
    addToHistory(result, 'solver');

    const s = result.stats;
    if (s.found) {
      showMessage('ok', `Solution found: ${s.moves} move${s.moves === 1 ? '' : 's'}, ${formatNumber(s.expanded)} ` +
        `nodes expanded in ${formatTime(s.timeMs)}.`);
    } else {
      showMessage('error', `No solution: BFS emptied the frontier after storing ${formatNumber(s.stored)} states ` +
        'without reaching the goal.');
    }
    loadResult();
    // on a phone, bring the visualization into view
    if (window.innerWidth < 992) $('tabSearch').scrollIntoView({ behavior: 'smooth', block: 'start' });
  }, 30);
}

function loadResult() {
  $('emptyState').hidden = true;
  drawBoard($('trioStart'), result.start);
  drawBoard($('trioGoal'), result.goal);

  buildPathList();
  renderSummary();
  renderHeuristics();

  searchPlayer.load(result.steps.length);
  solutionPlayer.load(result.path.length);
  $('tabSolution').disabled = !result.found;

  if (result.steps.length === 0) { // start already equals the goal
    setPhase('solution');
  } else {
    setPhase('search');
    searchPlayer.play();
  }
}

// ================= Phase (search process / solution path) =================
function setPhase(newPhase) {
  if (newPhase === 'solution' && (!result || !result.found)) return;
  searchPlayer.stop();
  solutionPlayer.stop();
  phase = newPhase;
  $('tabSearch').classList.toggle('active', phase === 'search');
  $('tabSolution').classList.toggle('active', phase === 'solution');
  $('tabSearch').setAttribute('aria-selected', phase === 'search');
  $('tabSolution').setAttribute('aria-selected', phase === 'solution');
  $('searchView').hidden = phase !== 'search';
  $('solutionView').hidden = phase !== 'solution';

  const player = activePlayer();
  if (player.frameCount > 0) player.goTo(player.position);
  else renderEmptySearch();
  updateControls();
}

function activePlayer() {
  return phase === 'search' ? searchPlayer : solutionPlayer;
}

function renderEmptySearch() {
  $('searchView').hidden = false;
  $('curBoard').innerHTML = '';
  $('childrenBox').innerHTML = '<p class="small text-secondary">The initial state already equals the goal, so BFS ' +
    'stops before expanding anything (1 node generated, 0 expanded).</p>';
}

// ================= Rendering one search step =================
function renderSearchStep(k) {
  const step = describeStep(result, k);
  const node = step.node;

  $('curIndex').textContent = step.index;
  drawBoard($('curBoard'), node.state, { compareTo: result.goal });
  $('curDepth').textContent = node.depth;
  $('curCost').textContent = node.depth;
  $('curMove').textContent = node.move || 'start';
  drawBoard($('trioCurrent'), node.state);
  $('trioCurrentLabel').textContent = `Current (node #${step.index})`;

  // parent
  const parentBox = $('parentBox');
  parentBox.innerHTML = '';
  if (step.parent) {
    parentBox.appendChild(makeMiniBoard(step.parent.state, `#${node.parent} · depth ${step.parent.depth}`));
  } else {
    parentBox.innerHTML = '<p class="small text-secondary mb-0">None &ndash; this is the start node.</p>';
  }

  // successors
  const childrenBox = $('childrenBox');
  childrenBox.innerHTML = '';
  for (const child of step.children) {
    const label = child.status === 'repeat' ? `${child.move} · repeat` : `${child.move} → #${child.index}`;
    childrenBox.appendChild(makeMiniBoard(child.state, label, 'status-' + child.status));
  }

  // live statistics
  const stats = [
    ['Nodes generated', formatNumber(step.generated)],
    ['Nodes expanded', formatNumber(step.expanded)],
    ['Repeats skipped', formatNumber(step.repeats)],
    ['Frontier size', formatNumber(step.frontierSize)],
    ['Explored size', formatNumber(step.exploredSize)],
    ['Current depth', node.depth],
  ];
  $('liveStats').innerHTML = stats.map(([label, value]) =>
    `<div><span>${label}</span><b class="mono">${value}</b></div>`).join('');

  // frontier: first 12 nodes waiting in the queue
  fillStrip($('frontierStrip'), step.frontierStart, step.frontierEnd, false);
  $('frontierCount').textContent = formatNumber(step.frontierSize);
  // explored: the 12 most recently expanded nodes
  fillStrip($('exploredStrip'), 0, step.exploredSize, true);
  $('exploredCount').textContent = formatNumber(step.exploredSize);

  $('stepLabel').textContent = `Expansion ${formatNumber(k + 1)} of ${formatNumber(result.steps.length)}`;
  $('scrubber').value = k;
}

function fillStrip(strip, from, to, newestFirst) {
  const SHOW = 12;
  strip.innerHTML = '';
  const total = to - from;
  const indexes = [];
  if (newestFirst) for (let i = to - 1; i >= Math.max(from, to - SHOW); i--) indexes.push(i);
  else for (let i = from; i < Math.min(to, from + SHOW); i++) indexes.push(i);

  for (const i of indexes) {
    const node = result.nodes[i];
    const extra = node.state === result.goal ? 'status-goal' : '';
    strip.appendChild(makeMiniBoard(node.state, `#${i} · d${node.depth}`, extra));
  }
  if (total > SHOW) {
    const more = document.createElement('div');
    more.className = 'more-chip';
    more.textContent = `+${formatNumber(total - SHOW)} more`;
    strip.appendChild(more);
  }
  if (total === 0) strip.innerHTML = '<span class="small text-secondary">empty</span>';
}

// ================= Rendering one solution step =================
function buildPathList() {
  const list = $('pathList');
  list.innerHTML = '';
  result.path.forEach((p, i) => {
    const item = document.createElement('li');
    item.appendChild(makeMiniBoard(p.state));
    const text = document.createElement('div');
    text.innerHTML = `<b>Step ${i}</b><span>${i === 0 ? 'initial state' : 'blank ' + p.move.toLowerCase()}</span>`;
    item.appendChild(text);
    item.addEventListener('click', () => { solutionPlayer.stop(); solutionPlayer.goTo(i); });
    list.appendChild(item);
  });
}

function renderSolutionStep(i) {
  const total = result.path.length - 1;
  const p = result.path[i];
  animatedBoard.show(p.state, result.goal);
  drawBoard($('trioCurrent'), p.state);
  $('trioCurrentLabel').textContent = `Current (step ${i})`;
  $('solTag').textContent = i === total ? `Step ${i} of ${total} — goal reached` : `Step ${i} of ${total}`;
  $('solMoveText').textContent = i === 0 ? 'Initial state' : `Blank moved ${p.move}`;

  const items = $('pathList').children;
  for (let j = 0; j < items.length; j++) items[j].classList.toggle('active', j === i);
  const active = items[i];
  const list = $('pathList');
  if (active) list.scrollTop = active.offsetTop - list.offsetTop - list.clientHeight / 2 + active.clientHeight / 2;

  $('stepLabel').textContent = `Solution step ${i} of ${total}`;
  $('scrubber').value = i;
}

// ================= Controls =================
function updateControls() {
  const player = activePlayer();
  const loaded = result !== null && player.frameCount > 0;
  const atEnd = player.position >= player.frameCount - 1;
  $('btnPlay').disabled = !loaded || player.playing;
  $('btnPause').disabled = !player.playing;
  $('btnResume').disabled = !loaded || player.playing || player.position === 0 || atEnd;
  $('btnNext').disabled = !loaded || atEnd;
  $('btnPrev').disabled = !loaded || player.position === 0;
  $('btnReset').disabled = result === null;

  const scrubber = $('scrubber');
  scrubber.disabled = !loaded || player.frameCount < 2;
  scrubber.max = Math.max(0, player.frameCount - 1);
  if (!loaded && result === null) $('stepLabel').textContent = 'No search yet';
}

function setSpeed() {
  const ms = SPEEDS_MS[Number($('speed').value) - 1];
  $('speedLabel').textContent = ms + ' ms';
  searchPlayer.delay = ms;
  solutionPlayer.delay = Math.max(ms, 60); // tiles need a moment to slide
  animatedBoard.setDuration(Math.min(350, Math.round(solutionPlayer.delay * 0.8)));
}

function resetAll() {
  searchPlayer.stop();
  solutionPlayer.stop();
  result = null;
  searchPlayer.load(0);
  solutionPlayer.load(0);
  $('searchView').hidden = true;
  $('solutionView').hidden = true;
  $('summaryCard').hidden = true;
  $('emptyState').hidden = false;
  ['trioStart', 'trioGoal', 'trioCurrent'].forEach(id => { $(id).innerHTML = ''; });
  $('trioCurrentLabel').textContent = 'Current';
  phase = 'search';
  $('tabSearch').classList.add('active');
  $('tabSolution').classList.remove('active');
  $('tabSolution').disabled = false;
  $('stepLabel').textContent = 'No search yet';
  clearMessage();
  updateControls();
}

// ================= Summary =================
function renderSummary() {
  const s = result.stats;
  const items = [
    ['Result', s.found ? 'Solution found' : 'Not found', s.found ? 'good' : 'bad'],
    ['Total moves', s.found ? s.moves : '–'],
    ['Path cost', s.found ? s.pathCost : '–'],
    ['Nodes generated', formatNumber(s.generated)],
    ['Nodes expanded', formatNumber(s.expanded)],
    ['Repeats skipped', formatNumber(s.repeats)],
    ['Max search depth', s.maxDepth],
    ['Peak frontier', formatNumber(s.maxFrontier)],
    ['Execution time', formatTime(s.timeMs)],
    ['Memory (approx.)', formatMemory(s.memoryKB) + ` (${formatNumber(s.stored)} nodes)`],
  ];
  $('summaryGrid').innerHTML = items.map(([label, value, cls]) =>
    `<div class="${cls || ''}"><span>${label}</span><b>${value}</b></div>`).join('');
  $('summaryCard').hidden = false;
}

// Browsers round performance.now() (often to 0.1 ms) for security reasons,
// so very fast searches can measure as 0.
function formatTime(ms) {
  return ms < 0.1 ? '< 0.1 ms' : ms.toFixed(1) + ' ms';
}

function formatMemory(kb) {
  return kb >= 1024 ? (kb / 1024).toFixed(1) + ' MB' : kb.toFixed(1) + ' KB';
}

// ================= Comparison page =================
function addToHistory(r, source) {
  runHistory.push({ start: r.start, goal: r.goal, stats: r.stats, source });
  renderHistory();
}

function renderHistory() {
  const body = $('historyBody');
  if (runHistory.length === 0) {
    body.innerHTML = '<tr><td colspan="10" class="text-secondary">No runs yet.</td></tr>';
    $('growthChart').hidden = true;
    return;
  }
  body.innerHTML = runHistory.map((h, i) => {
    const s = h.stats;
    return `<tr>
      <td>${i + 1}${h.source === 'benchmark' ? ' <span class="badge text-bg-light">bench</span>' : ''}</td>
      <td class="mono small">${h.start} &rarr; ${h.goal}</td>
      <td>${s.found ? 'Yes' : 'No'}</td>
      <td>${s.found ? s.moves : '–'}</td>
      <td>${formatNumber(s.generated)}</td>
      <td>${formatNumber(s.expanded)}</td>
      <td>${s.maxDepth}</td>
      <td>${formatNumber(s.maxFrontier)}</td>
      <td>${formatTime(s.timeMs).replace(' ms', '')}</td>
      <td>${formatMemory(s.memoryKB)}</td>
    </tr>`;
  }).join('');
  drawGrowthChart();
}

// Small SVG chart: nodes expanded (log scale) against solution length.
function drawGrowthChart() {
  const points = runHistory.filter(h => h.stats.found && h.stats.moves > 0)
    .map(h => ({ x: h.stats.moves, y: h.stats.expanded }));
  const box = $('growthChart');
  if (points.length < 3) { box.hidden = true; return; }

  const W = 640, H = 240, L = 78, R = 16, T = 16, B = 40;
  const maxX = Math.max(...points.map(p => p.x));
  const maxLog = Math.ceil(Math.log10(Math.max(...points.map(p => p.y))));
  const px = x => L + (x / maxX) * (W - L - R);
  const py = y => H - B - (Math.log10(Math.max(1, y)) / maxLog) * (H - T - B);

  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Nodes expanded versus solution length">`;
  for (let e = 0; e <= maxLog; e++) {
    const y = py(Math.pow(10, e));
    svg += `<line x1="${L}" x2="${W - R}" y1="${y}" y2="${y}" class="grid-line"/>` +
      `<text x="${L - 8}" y="${y + 4}" text-anchor="end">${formatNumber(Math.pow(10, e))}</text>`;
  }
  for (let x = 0; x <= maxX; x += 5) {
    svg += `<text x="${px(x)}" y="${H - B + 18}" text-anchor="middle">${x}</text>`;
  }
  svg += `<text x="${(L + W - R) / 2}" y="${H - 4}" text-anchor="middle" class="axis-title">solution length (moves)</text>`;
  for (const p of points) svg += `<circle cx="${px(p.x)}" cy="${py(p.y)}" r="5"><title>${p.x} moves: ${formatNumber(p.y)} expanded</title></circle>`;
  svg += '</svg>';
  box.innerHTML = '<div class="mini-heading">Nodes expanded (log scale) vs. solution length &mdash; measured</div>' + svg;
  box.hidden = false;
}

function runBenchmark() {
  const button = $('btnBenchmark');
  button.disabled = true;
  let i = 0;
  // one puzzle per timeout so the page stays responsive
  function nextPuzzle() {
    if (i >= BENCHMARK.length) { button.disabled = false; button.textContent = 'Run benchmark set'; return; }
    button.textContent = `Running ${i + 1}/${BENCHMARK.length}...`;
    addToHistory(bfsSolve(BENCHMARK[i], GOAL_PRESETS.spiral), 'benchmark');
    i++;
    setTimeout(nextPuzzle, 20);
  }
  nextPuzzle();
}

function renderHeuristics() {
  const s = result.stats;
  const h1 = misplacedTiles(result.start, result.goal);
  const h2 = manhattanDistance(result.start, result.goal);
  $('heuristicBox').innerHTML = `
    <div class="heuristic-row">
      <div><span>Misplaced tiles h&#8321;</span><b class="mono">${h1}</b></div>
      <div><span>Manhattan distance h&#8322;</span><b class="mono">${h2}</b></div>
      <div><span>True shortest distance (BFS)</span><b class="mono">${s.found ? s.moves : 'no solution'}</b></div>
    </div>
    <p class="mb-0 mt-2">Puzzle <span class="mono">${stateToText(result.start)}</span>.
    ${s.found ? `Both values are &le; ${s.moves}, as an admissible heuristic must be.` : ''}</p>`;
}

// ================= Home page illustration =================
function drawHomeBoards() {
  document.querySelectorAll('.board-static[data-state]').forEach(el => drawBoard(el, el.dataset.state));

  // Layers 0, 1 and 2 of BFS from the example start state.
  const preview = $('layerPreview');
  const seen = new Set([EXAMPLE_START]);
  let layer = [{ state: EXAMPLE_START, move: 'start' }];
  for (let depth = 0; depth <= 2; depth++) {
    const row = document.createElement('div');
    row.className = 'layer-row';
    row.innerHTML = `<div class="layer-label">depth ${depth}<small>${layer.length} state${layer.length > 1 ? 's' : ''}</small></div>`;
    const boards = document.createElement('div');
    boards.className = 'layer-boards';
    layer.forEach(item => boards.appendChild(makeMiniBoard(item.state, item.move)));
    row.appendChild(boards);
    preview.appendChild(row);

    const nextLayer = [];
    for (const item of layer) {
      for (const s of getSuccessors(item.state)) {
        if (!seen.has(s.state)) { seen.add(s.state); nextLayer.push(s); }
      }
    }
    layer = nextLayer;
  }
}

