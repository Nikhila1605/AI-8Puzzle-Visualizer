function showPage() {
  const name = location.hash.replace('#', '');
  const page = PAGES.includes(name) ? name : 'home';
  for (const p of PAGES) $('page-' + p).hidden = p !== page;
  document.querySelectorAll('.site-nav .nav-link').forEach(link => {
    link.classList.toggle('active', link.dataset.page === page);
  });
  // close the mobile menu after choosing a page
  const menu = $('mainNav');
  if (menu.classList.contains('show') && window.bootstrap) bootstrap.Collapse.getOrCreateInstance(menu).hide();
  window.scrollTo(0, 0);
}

// ================= Grid inputs =================
function buildGridInput(container) {
  const name = container.dataset.name;
  for (let i = 0; i < 9; i++) {
    const input = document.createElement('input');
    input.type = 'text';
    input.inputMode = 'numeric';
    input.maxLength = 1;
    input.id = `${name}-${i}`;
    input.className = 'grid-cell';
    input.setAttribute('aria-label', `${name} row ${Math.floor(i / 3) + 1} column ${(i % 3) + 1}`);
    input.addEventListener('input', () => {
      input.value = input.value.slice(-1);
      input.classList.toggle('is-blank', input.value === '' || input.value === '0' || input.value === '_');
      if (input.value !== '' && i < 8) $(`${name}-${i + 1}`).focus(); // jump to next cell
      clearMessage();
    });
    input.addEventListener('keydown', event => {
      if (event.key === 'Enter') runSearch();
      if (event.key === 'Backspace' && input.value === '' && i > 0) $(`${name}-${i - 1}`).focus();
    });
    container.appendChild(input);
  }
}

function setGrid(name, state) {
  for (let i = 0; i < 9; i++) {
    const input = $(`${name}-${i}`);
    input.value = state[i] === '0' ? '' : state[i];
    input.classList.toggle('is-blank', state[i] === '0');
  }
}

function readGrid(name) {
  const cells = [];
  for (let i = 0; i < 9; i++) cells.push($(`${name}-${i}`).value);
  return cells;
}

